// Capture the website's reviewed public assets for standalone, reproducible Android builds.
import fs from 'node:fs';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..'),cloud=path.resolve(root,'../cloud');
execFileSync('git',['diff','--quiet','HEAD','--','public'],{cwd:cloud});
const sha=execFileSync('git',['rev-parse','HEAD'],{cwd:cloud,encoding:'utf8'}).trim();
const expected=process.env.LEDGER_EXPECTED_WEB_SHA;
if(!expected||sha!==expected)throw Error('Set LEDGER_EXPECTED_WEB_SHA to the explicitly approved website commit.');
const siteVersion=Number(process.env.LEDGER_SITE_VERSION);
if(!Number.isSafeInteger(siteVersion)||siteVersion<1)throw Error('Set the verified LEDGER_SITE_VERSION.');
const dest=path.join(root,'web-source');
fs.cpSync(path.join(cloud,'public'),dest,{recursive:true});
const sourceFiles=execFileSync('git',['ls-files','-z','public'],{cwd:cloud}).toString().split('\0').filter(Boolean);
const textFile=p=>/\.(?:js|json|html|css|md|svg|txt)$/i.test(p)||/\/(?:LICENSE|NOTICE)$/.test(p);
const files=sourceFiles.map(p=>{const rel=p.slice('public/'.length),kind=textFile(p)?'utf8-lf':'binary';let b=fs.readFileSync(path.join(dest,rel));if(kind==='utf8-lf')b=Buffer.from(b.toString('utf8').replace(/\r\n/g,'\n'));return{path:rel,kind,sha256:crypto.createHash('sha256').update(b).digest('hex')};});
fs.writeFileSync(path.join(dest,'SOURCE_MANIFEST.json'),JSON.stringify({gitSha:sha,siteVersion,files},null,2)+'\n');
fs.writeFileSync(path.join(dest,'UPSTREAM.json'),JSON.stringify({repository:'existing Vocabulary Ledger Sites source',gitSha:sha,siteVersion,source:'cloud/public',capturedAt:new Date().toISOString(),notes:'Website-only auth, community and online APIs are disabled by the offline adapter. Original source attribution retained.'},null,2)+'\n');
console.log('Captured reviewed public source',sha);
